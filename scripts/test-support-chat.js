"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const { buildAssistantReply } = require("../api-handlers/support-chat");
const api = fs.readFileSync("api-handlers/support-chat.js","utf8");
const widget = fs.readFileSync("support-widget.js","utf8");
const adminClient = fs.readFileSync("admin-support.js","utf8");
const adminPage = fs.readFileSync("admin.html","utf8");
const migration = fs.readFileSync("db/migrations/007_customer_support_chat.sql","utf8");
for (const role of ["customer","assistant","admin"]) assert.ok(migration.includes("'" + role + "'"));
assert.ok(migration.includes("REFERENCES vf_users(id)"));
assert.ok(!api.includes("OPENAI_API_KEY"), "Built-in help must not depend on a paid OpenAI key");
assert.ok(!api.includes("api.openai.com"));
assert.ok(api.includes("HANDOFF_RE"));
assert.ok(api.includes("VERIFYFLOW_ADMIN_EMAILS"));
assert.ok(api.includes("sameOrigin(req)"));
assert.ok(api.includes("status='human'"));
assert.ok(api.includes("support-guest-help"), "Guest help requests are rate limited");
assert.ok(api.includes("guest:true"), "Guests receive instant help without a saved conversation");
assert.ok(api.includes("signInUrl"), "Human handoff directs guests to sign in");
assert.match(buildAssistantReply("Where will my OTP code appear?"), /verification code/i);
assert.match(buildAssistantReply("My TikTok booster is not starting"), /target URL/i);
assert.match(buildAssistantReply("How do I reset my password?"), /Forgot password/i);
assert.match(buildAssistantReply("What is the weather?"), /Talk to customer support/i);
assert.ok(widget.includes("/api/support/chat"));
assert.ok(widget.includes("human.addEventListener"), "Customer can explicitly hand off to human support");
assert.ok(widget.includes("setInterval"));
assert.ok(widget.includes("guestMode"));
assert.ok(widget.includes("showSignInPrompt"));
assert.ok(!widget.includes("AI assistant"), "Widget must not claim to use a paid generative AI provider");
assert.ok(adminClient.includes("/api/admin/support"));
assert.ok(adminClient.includes("loadThread()"), "Open admin thread polls for new replies");
assert.ok(adminPage.includes('id="customer-support-inbox"'));
assert.ok(adminPage.includes("/admin-support.js"));
console.log("Customer support chat tests passed (built-in replies, handoff and live admin thread polling).");
