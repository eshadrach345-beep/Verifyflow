"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const read = path => fs.readFileSync(path, "utf8");

const payment = read("lib/payment-service.js");
const orderCreate = read("api-handlers/orders/create.js");
const fulfilment = read("lib/fulfilment.js");
const voidmob = read("lib/voidmob.js");
const herosms = read("lib/herosms.js");
const smm = read("lib/smm-service.js");
const catalog = read("api-handlers/catalog.js");
const checkout = read("dashboard-checkout.js");
const refresh = read("api-handlers/orders/refresh.js");

assert.ok(payment.includes("verifyAndApplyPayment"));
assert.ok(payment.includes("enqueuePaidOrder"));
assert.ok(payment.includes("processFulfilmentForOrder"), "Verified Monnify payments enter fulfilment");
assert.ok(orderCreate.includes("FROM vf_smm_products"), "SMM routing uses the saved admin-selected product");
assert.ok(orderCreate.includes("selectedProvider = String(product.provider)"), "Customer cannot override saved SMM supplier selection");
assert.ok(orderCreate.includes("supplierInput"));
assert.ok(fulfilment.includes("placeSmmOrder"));
assert.ok(fulfilment.includes("buyHeroSmsNumber"));
assert.ok(fulfilment.includes("buyHeroSmsRental"));
assert.ok(fulfilment.includes("await purchase(job.product_type"));
assert.ok(voidmob.includes('sms_otp: "/verifications/"'));
assert.ok(voidmob.includes('long_term_number: "/rentals/"'));
assert.ok(voidmob.includes('dedicated_number: "/dedicated/numbers/"'));
assert.ok(voidmob.includes('esim: "/esims/"'));
assert.ok(voidmob.includes('mobile_proxy: "/proxies/"'));
assert.ok(herosms.includes('request("getNumberV2"'));
assert.ok(herosms.includes('request("getRentNumber"'));
assert.ok(herosms.includes('request("getStatusV2"'));
assert.ok(herosms.includes('request("getRentStatus"'));
assert.ok(smm.includes('action: "add"'));
assert.ok(smm.includes('action: "status"'));
assert.ok(smm.includes("service, link, quantity"));
assert.ok(catalog.includes("heroSmsRentalItems"), "HeroSMS long-term numbers remain part of the merged retail catalogue");
assert.ok(catalog.includes("sealCatalogProductToken") && orderCreate.includes("openCatalogProductToken"), "Supplier selections are encrypted for customers and resolved server-side");
assert.ok(orderCreate.includes("error.status === 400") && orderCreate.includes("INVALID_CATALOG_SELECTION"), "Invalid or tampered catalogue selections must return a client error");
assert.ok(!checkout.includes("data-provider=") && !checkout.includes("data-country="), "Checkout DOM must not expose supplier routing attributes");
assert.ok(!checkout.includes('if (category === "rentals" && item.provider === "herosms") return null;'));
assert.ok(checkout.includes('fetch("/api/orders/create"'));
assert.ok(orderCreate.includes("getCheckoutAmount(quote.salePriceCents)"), "Checkout must convert USD catalogue prices to the account-enabled payment currency");
assert.ok(orderCreate.includes("paymentAmountMinor") && orderCreate.includes("paymentCurrency"), "Monnify request and stored payment must use the same actual currency amount");
assert.ok(refresh.includes("refreshOrderFromSupplier"));
assert.ok(fulfilment.includes('env.MONNIFY_ENVIRONMENT || "").toUpperCase() !== "LIVE"'));
console.log("Order routing audit passed (payment verification, all supplier adapters, SMM submit/status and launch locks).");
